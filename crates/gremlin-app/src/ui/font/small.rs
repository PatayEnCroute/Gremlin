//! Dessins du corps compact 6×11.
//!
//! # Métrique verticale, sur onze lignes (0 à 10)
//!
//! | Lignes | Rôle |
//! | --- | --- |
//! | 0-1  | accents des capitales |
//! | 1-2  | accents des minuscules |
//! | 2-8  | hauteur de capitale (7 px) |
//! | 3    | ligne libre séparant l'accent de l'œil |
//! | 4-8  | hauteur d'œil des minuscules (5 px) |
//! | 8    | ligne de base |
//! | 9-10 | jambages descendants et cédille |
//!
//! # À quoi sert ce corps
//!
//! En-têtes de section, pastilles de statut, sous-titres et pied de page. Son
//! absence faisait servir le corps moyen 8×15 à sa place : les libellés de
//! section entraient alors en collision avec les pastilles sur une même ligne de
//! liste, faute de tenir dans la hauteur que la maquette leur réserve.
//!
//! Les conventions de dessin sont celles du module parent : `.` vide, `:` léger,
//! `+` marqué, `#` plein.

