/// Repli ASCII pour les caractères sans glyphe dédié.
///
/// Afficher « E » à la place de « É » reste très supérieur au « ? » générique
/// utilisé auparavant : les majuscules accentuées occupent les sept lignes du
/// glyphe et ne laissent aucune place à l'accent.
const fn fold_to_ascii(ch: char) -> Option<char> {
    match ch {
        'É' | 'È' | 'Ê' | 'Ë' => Some('E'),
        'À' | 'Â' | 'Ä' | 'Æ' => Some('A'),
        'Ù' | 'Û' | 'Ü' => Some('U'),
        'Î' | 'Ï' => Some('I'),
        'Ô' | 'Ö' | 'Œ' | 'Ø' => Some('O'),
        'Ç' => Some('C'),
        'œ' | 'ø' => Some('o'),
        'æ' => Some('a'),
        'ÿ' => Some('y'),
        'ñ' => Some('n'),
        '…' => Some('.'),
        '“' | '”' => Some('"'),
        '‘' => Some('\''),
        '–' => Some('-'),
        _ => None,
    }
}

/// Motif du glyphe correspondant à un caractère, avec repli documenté.
fn glyph_for(ch: char) -> [u8; 5] {
    let ascii = ch as usize;
    if (32..=126).contains(&ascii) {
        return FONT_5X7[ascii - 32];
    }

    if let Some((_, glyph)) = ACCENTED_GLYPHS.iter().find(|(c, _)| *c == ch) {
        return *glyph;
    }

    if let Some(folded) = fold_to_ascii(ch) {
        let folded_ascii = folded as usize;
        if (32..=126).contains(&folded_ascii) {
            return FONT_5X7[folded_ascii - 32];
        }
    }

    FONT_5X7[31] // '?' pour les caractères réellement non supportés
}

/// Largeur en pixels occupée par `text` une fois rendu.
///
/// Compte les caractères et non les octets : une chaîne accentuée serait sinon
/// surestimée, ce qui décalait le curseur de la barre de recherche.
#[must_use]
pub fn text_width_px(text: &str) -> i32 {
    let chars = text.chars().filter(|c| *c != '\n').count();
    i32::try_from(chars.saturating_mul(GLYPH_ADVANCE)).unwrap_or(i32::MAX)
}

/// Dessine une chaîne de caractères avec la police 5x7 dans un tampon RGBA.
pub fn draw_text_5x7(
    buf: &mut [u8],
    buf_width: usize,
    buf_height: usize,
    text: &str,
    start_x: i32,
    start_y: i32,
    color: [u8; 4],
) {
    let mut cursor_x = start_x;

    for ch in text.chars() {
        if ch == '\n' {
            continue;
        }

        let glyph_data = glyph_for(ch);

        for (col_idx, &col_byte) in glyph_data.iter().enumerate() {
            let px = cursor_x + (col_idx as i32);
            if px < 0 || px >= (buf_width as i32) {
                continue;
            }

            for row_idx in 0..GLYPH_HEIGHT {
                let py = start_y + (row_idx as i32);
                if py < 0 || py >= (buf_height as i32) {
                    continue;
                }

                if (col_byte & (1 << row_idx)) != 0 {
                    let idx = ((py as usize) * buf_width + (px as usize)) * 4;
                    if idx + 3 < buf.len() {
                        buf[idx] = color[0];
                        buf[idx + 1] = color[1];
                        buf[idx + 2] = color[2];
                        buf[idx + 3] = color[3];
                    }
                }
            }
        }

        // Espacement de 1 pixel entre les lettres
        cursor_x += GLYPH_ADVANCE as i32;
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn render(text: &str) -> Vec<u8> {
        let mut buf = vec![0_u8; 64 * 16 * 4];
        draw_text_5x7(&mut buf, 64, 16, text, 0, 2, [255, 255, 255, 255]);
        buf
    }

    #[test]
    fn test_text_width_counts_characters_not_bytes() {
        // « Dépôt » fait 7 octets mais 5 caractères.
        assert_eq!("Dépôt".len(), 7);
        assert_eq!(text_width_px("Dépôt"), 5 * GLYPH_ADVANCE as i32);
        assert_eq!(text_width_px(""), 0);
    }

    #[test]
    fn test_accented_lowercase_have_dedicated_glyphs() {
        for ch in ['é', 'è', 'ê', 'à', 'ç', 'ô', 'û', 'î'] {
            let glyph = glyph_for(ch);
            assert_ne!(
                glyph, FONT_5X7[31],
                "le caractère « {ch} » retombe encore sur '?'"
            );
        }
    }

    #[test]
    fn test_uppercase_accents_fold_to_base_letter() {
        assert_eq!(glyph_for('É'), glyph_for('E'));
        assert_eq!(glyph_for('À'), glyph_for('A'));
        assert_eq!(glyph_for('Ç'), glyph_for('C'));
    }

    #[test]
    fn test_accented_text_actually_draws_pixels() {
        assert!(render("Énergie écoulée").iter().any(|&b| b > 0));
    }

    #[test]
    fn test_drawing_never_panics_on_exotic_input() {
        // Emoji, idéogrammes et caractères de contrôle doivent être tolérés.
        let _ = render("🐉漢字\u{0}\u{7f}");
    }
}
